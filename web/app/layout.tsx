// Shared across the meta description, OG, and Twitter card so a link to
// the site renders a real title card on Discord/social (the open-border funnel
// depends on that share surface not being blank). The OG/Twitter image is
// generated by app/opengraph-image.tsx and wired in automatically by Next.
// Install key site.description; unset = a neutral line.
// generateMetadata, not a `metadata` object: the values are this install's, read when the server
// starts (installValues.ts), and a module-level object would be evaluated during `next build` too,
// where there is no install at all.
export function generateMetadata(): Metadata {
  const description = installValue("site.description") || `${siteName()} — a live stream and its community, with chat unified across every platform.`;
  // The product's favicon.ico, only while the install uses the product's own icon set.
  const productIco = productFavicon();
  return {
    metadataBase: new URL(installValue("site.origin")),
    title: siteName(),
    description,
    appleWebApp: {
      capable: true,
      title: siteName(),
      statusBarStyle: "black-translucent",
    },
    // The install's icons (install key site.iconSet; unset = the product's own set, which also has a
    // favicon.ico). The manifest link comes from app/manifest.ts, which Next links by itself.
    icons: {
      icon: [
        ...(productIco ? [{ url: productIco, sizes: "16x16 32x32 48x48" }] : []),
        { url: siteIcon("icon.png"), type: "image/png", sizes: "512x512" },
      ],
      apple: siteIcon("apple-touch-icon.png"),
    },
    openGraph: {
      type: "website",
      siteName: siteName(),
      title: siteName(),
      description,
      url: "/",
      locale: "en_US",
    },
    twitter: {
      card: "summary_large_image",
      title: siteName(),
      description,
    },
  };
}

export const viewport: Viewport = {
  themeColor: "#0c1020",
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
  // `resizes-content`: the LAYOUT viewport shrinks with the keyboard, so
  // visual == layout and the page CANNOT be panned while typing (under
  // resizes-visual, dragging the chat input bar pushes the video panel out of
  // view, on Chrome and Firefox tabs). It is the canonical mode for exactly
  // this layout (the viewport-resize-behavior explainer's chat-app example)
  // and the model Firefox Android natively uses. dvh follows the keyboard
  // under it, so the `.h-app` fallback tier is correct even before any JS
  // runs.
  //
  // Not `overlays-content`: Firefox honours it (132+) but has no
  // VirtualKeyboard API — NEITHER viewport resizes, so the keyboard is a total
  // blind spot — and Chrome's env(keyboard-inset-height) reads a constant ~16
  // CSS px SHORT of the real occlusion (nav-gesture zone excluded;
  // safe-area-inset-bottom is 0, so CSS cannot recover it), leaving the
  // composer half-hidden under the keyboard in tabs. The API's geometry is
  // documented-broken: zouhir.org/blog/virtual-keyboard-api, interop#1016,
  // crbug 40924170.
  //
  // The usual objection to resizes-content (the resize lands as one step at
  // the END of the keyboard's slide-in) is answered by the focus-time
  // PREDICTION in useViewportHeightVar: the shell moves instantly on the
  // guess, and the browser's real resize supersedes it at settle with the
  // exact value.
  //
  // The one place the env() tier still runs is the installed PWA: the hook
  // opts it back into overlay via navigator.virtualKeyboard.overlaysContent =
  // true, which per spec takes precedence over this meta.
  interactiveWidget: "resizes-content",
};

