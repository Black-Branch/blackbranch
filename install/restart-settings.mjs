// The settings that apply only when the service reading them restarts (`reload: 'restart'` in
// config/instance-schema.mjs), as ONE list for the operator. The Admin Panel says "applies at
// restart" beside each such key; this is the whole list in one place, where an operator meets it:
// `blackbranch help` prints it, `blackbranch status` names the ones changed since their service
// started, and docs/public/operate.md carries it.
//
//   node install/restart-settings.mjs            print the list (the same text `blackbranch help` shows)
//   node install/restart-settings.mjs --write    regenerate install/restart-settings.tsv and the
//                                                 section of docs/public/operate.md between its markers
//   node install/restart-settings.mjs --check    exit 1 when either has drifted from the schema
//
// The box has no Node, so the command reads the generated install/restart-settings.tsv (it ships
// with every release). install/restart-settings.test.mjs fails when either copy drifts.
//
// Where each setting is changed decides what the operator does after:
//   panel      Admin Panel (an instance or secret setting): restart the services named.
//   set        .env, a display value `blackbranch set` changes: it restarts what reads it itself.
//   permanent  .env, the install's identity (its addresses, its chat server's name): never changes.
// An install-tier key this bundle's .env never holds (install/.env.example) is left out: an operator
// of this bundle cannot set it (the legacy keys of the first install, the Discord bridge's templates
// until the bridge ships, OBS's and Home Assistant's addresses, the derived federation address).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { INSTANCE_KEYS } from "../config/instance-schema.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const TSV = path.join(here, "restart-settings.tsv");
const DOC = path.join(here, "../docs/public/operate.md");
export const DOC_START = "<!-- restart-settings: generated by install/restart-settings.mjs; edit the schema, then run it with --write -->";
export const DOC_END = "<!-- /restart-settings -->";
const GROUPS = ["panel", "set", "permanent"];

const envKeys = (text) => new Set([...text.matchAll(/^([A-Z][A-Z0-9_]*)=/gm)].map((m) => m[1]));
function settableKeys() {
  const m = readFileSync(path.join(here, "blackbranch"), "utf8").match(/\nSETTABLE_KEYS=\(\n?([\s\S]*?)\n?\)/);
  if (!m) throw new Error("restart-settings: SETTABLE_KEYS not found in install/blackbranch");
  return new Set(m[1].split(/\s+/).filter(Boolean));
}

/** Every restart-only setting an operator of this bundle can change, grouped, in a fixed order. */
export function restartSettings(keys = INSTANCE_KEYS) {
  const inEnv = envKeys(readFileSync(path.join(here, ".env.example"), "utf8"));
  const settable = settableKeys();
  const rows = [];
  for (const k of keys) {
    if (k.reload !== "restart") continue;
    let group;
    if (k.tier === "instance" || k.tier === "secret") group = "panel";
    else if (inEnv.has(k.env[0])) group = settable.has(k.env[0]) ? "set" : "permanent";
    else continue;
    rows.push({ key: k.key, group, env: group === "panel" ? "" : k.env[0], services: [...k.packages], label: k.label });
  }
  // By group, then by the name the operator reads: the setting's key in the Admin Panel, its .env key otherwise.
  const name = (r) => r.env || r.key;
  return rows.sort((a, b) => GROUPS.indexOf(a.group) - GROUPS.indexOf(b.group) || (name(a) < name(b) ? -1 : name(a) > name(b) ? 1 : 0));
}

export function tsv(rows = restartSettings()) {
  // Tabs and line breaks never reach a field: the command splits on the tab.
  const clean = (s) => String(s).replace(/[\t\r\n]/g, " ");
  return ["# GENERATED by install/restart-settings.mjs from config/instance-schema.mjs: never edit by hand.",
    "# key\tgroup\tenv\tservices\tlabel",
    ...rows.map((r) => [r.key, r.group, r.env || "-", r.services.join(","), r.label].map(clean).join("\t"))].join("\n") + "\n";
}

/** The list as the operator reads it (plain text: `blackbranch help` prints this same shape from the tsv). */
export function text(rows = restartSettings()) {
  const out = [`Settings that apply only when their service restarts (${rows.length}):`];
  const by = (g) => rows.filter((r) => r.group === g);
  out.push("  Changed in the Admin Panel: afterwards run sudo blackbranch restart <service> for each service named.");
  for (const r of by("panel")) out.push(`    ${r.key.padEnd(30)} ${r.services.join(", ").padEnd(26)} ${r.label}`);
  out.push("  Display values in .env: sudo blackbranch set <KEY> <value> restarts what reads them.");
  for (const r of by("set")) out.push(`    ${r.env.padEnd(30)} ${r.services.join(", ").padEnd(26)} ${r.label}`);
  out.push("  The install's identity in .env: permanent, never change these.");
  for (const r of by("permanent")) out.push(`    ${r.env.padEnd(30)} ${r.services.join(", ").padEnd(26)} ${r.label}`);
  return out.join("\n") + "\n";
}

/** The section of docs/public/operate.md between the markers (the markers included). */
export function markdown(rows = restartSettings()) {
  const by = (g) => rows.filter((r) => r.group === g);
  const table = (list, name) => [`| ${name} | Restart | What it is |`, "|---|---|---|",
    ...list.map((r) => `| \`${r.group === "panel" ? r.key : r.env}\` | ${r.services.map((s) => `\`${s}\``).join(", ")} | ${r.label} |`)];
  return [DOC_START,
    "",
    `These ${rows.length} settings are read once, when the service that uses them starts. Changing one does`,
    "nothing until that service restarts. The Admin Panel says \"applies at restart\" beside each of its own;",
    "this is the whole list in one place. `sudo blackbranch help` prints it too, and `sudo blackbranch status`",
    "names any that were changed in the Admin Panel after their service last started.",
    "",
    "**Changed in the Admin Panel.** After you change one, restart each service in its row:",
    "`sudo blackbranch restart <service>`.",
    "",
    ...table(by("panel"), "Setting"),
    "",
    "**Display values in `.env`.** Change them with `sudo blackbranch set <KEY> <value>`: it restarts what",
    "reads them for you. If you edit `.env` by hand instead, run `sudo blackbranch up` afterwards (a plain",
    "restart keeps the old value).",
    "",
    ...table(by("set"), "Key in `.env`"),
    "",
    "**The install's identity in `.env`.** These are permanent: the chat server's name and the site's",
    "addresses can never change. They are listed so you know not to.",
    "",
    ...table(by("permanent"), "Key in `.env`"),
    "",
    DOC_END].join("\n");
}

function docWith(section, doc = readFileSync(DOC, "utf8")) {
  const a = doc.indexOf(DOC_START), b = doc.indexOf(DOC_END);
  if (a < 0 || b < a) throw new Error(`restart-settings: ${path.relative(process.cwd(), DOC)} has no generated section (the two markers)`);
  return doc.slice(0, a) + section + doc.slice(b + DOC_END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = process.argv[2] ?? "";
  if (arg === "--write") {
    writeFileSync(TSV, tsv());
    writeFileSync(DOC, docWith(markdown()));
    process.stdout.write(`wrote install/restart-settings.tsv and docs/public/operate.md (${restartSettings().length} settings)\n`);
  } else if (arg === "--check") {
    const drift = [];
    if (readFileSync(TSV, "utf8") !== tsv()) drift.push("install/restart-settings.tsv");
    const doc = readFileSync(DOC, "utf8");
    if (docWith(markdown(), doc) !== doc) drift.push("docs/public/operate.md");
    if (drift.length) { process.stderr.write(`restart-settings: ${drift.join(" and ")} drifted from the schema; run: node install/restart-settings.mjs --write\n`); process.exit(1); }
  } else if (arg === "") {
    process.stdout.write(text());
  } else {
    process.stderr.write("usage: node install/restart-settings.mjs [--write|--check]\n"); process.exit(2);
  }
}
