#!/usr/bin/env node
// The per-platform setup pages of the public docs (docs/public/platforms/*.md), GENERATED from the
// same setup lists the setup pages and the Admin Panel's guides are drawn from: SETUP_CORE in
// config/setup-core.mjs and each product module's `setup` in config/modules.mjs. One source, so the
// docs and the wizard cannot say different things.
//
//   node tools/gen-platform-docs.mjs           write docs/public/platforms/
//   node tools/gen-platform-docs.mjs --check   exit 1 when any page differs from what it would write,
//                                              or a page exists that no list makes (CI runs this)
//
// The values to paste are shown for an install at example.com — the setup page computes them from
// the install's own domain. Never edit a generated page by hand: edit the list and regenerate.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SETUP_CORE, setupProblems } from "../config/setup-core.mjs";
import { MODULES } from "../config/modules.mjs";
import { INSTANCE_KEYS } from "../config/instance-schema.mjs";

const REPO = resolve(fileURLToPath(import.meta.url), "../..");
export const OUT_DIR = join(REPO, "docs", "public", "platforms");

/** How a page shows the values the setup page computes from the install's domain. */
export const EXAMPLE = {
  origin: "https://example.com",
  apiOrigin: "https://api.example.com",
  domain: "example.com",
  matrixOrigin: "https://matrix.example.com",
  serverName: "example.com",
};

const GENERATED = "<!-- GENERATED by tools/gen-platform-docs.mjs from config/setup-core.mjs and config/modules.mjs — do not edit; edit the setup list and regenerate. -->";

/** Prose for Markdown: an angle bracket would start an HTML tag and hide the text. @param {string} v */
const prose = (v) => v.replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** Prose inside a table cell: a backslash is escaped before the pipe, so `\|` cannot become an escaped backslash and a bare pipe. */
const proseCell = (v) => prose(v).replace(/\\/g, "\\\\").replace(/\|/g, "\\|");

/** @param {string} v */
const fill = (v) => v.replace(/\{([a-zA-Z]+)\}/g, (_, k) => EXAMPLE[k] ?? `{${k}}`);

/**
 * Every setup list the public docs describe: each product module that has one, then the core lists.
 * @returns {{ id: string, label: string, description: string, kind: "module" | "core", release: string, defaultOn?: boolean, steps: any[] }[]}
 */
export function setupLists() {
  const modules = MODULES.filter((m) => m.kind === "module" && Array.isArray(m.setup)).map((m) => ({
    id: m.id, label: m.label, description: m.description, kind: /** @type {const} */ ("module"),
    // An ownerOnly step is never shown to a public install, so the public docs leave it out too.
    release: "now", defaultOn: m.defaultOn, steps: m.setup.filter((st) => st.ownerOnly !== true),
  }));
  const core = SETUP_CORE.map((c) => ({
    id: c.id, label: c.label, description: c.description, kind: /** @type {const} */ ("core"), release: c.release, steps: c.steps,
  }));
  return [...core, ...modules];
}

/** @param {string} key */
function field(key) {
  const e = INSTANCE_KEYS.find((k) => k.key === key);
  if (!e) throw new Error(`gen-platform-docs: ${key} is not a settings key`);
  const kept = e.secret ? " (kept encrypted)" : "";
  return `- **${prose(e.label)}**${kept}. ${prose(e.description)}`;
}

/** One list's page. */
export function renderPage(list) {
  const lines = [GENERATED, "", `# ${prose(list.label)}`, "", prose(list.description), ""];
  if (list.release === "later") lines.push("> This part arrives in a later release.", "");
  if (list.kind === "module") {
    lines.push(
      `This is a module: switch it on during setup (the **Modules** page) or later in the Admin Panel → Site → Modules${list.defaultOn ? "" : " — it is off on a new install"}. Its setup page then appears with the steps below.`,
      "",
    );
  } else {
    lines.push("Choose it during setup on the **Modules** page; its setup page then appears with the steps below. The same steps are in the Admin Panel later.", "");
  }
  lines.push(`The addresses below are for a site at \`${EXAMPLE.domain}\`; your setup page shows your own.`, "");
  list.steps.forEach((s, i) => {
    lines.push(`## ${i + 1}. ${prose(s.title)}${s.need === "optional" ? " (optional)" : ""}`, "", prose(s.explain), "");
    if (s.links.length) {
      lines.push("Links:", "", ...s.links.map((l) => `- [${prose(l.label)}](${l.url})`), "");
    }
    if (s.paste.length) {
      lines.push("Copy into the provider's page:", "", "| What | Value |", "|---|---|",
        ...s.paste.map((p) => `| ${prose(p.label)} | \`${fill(p.value).replace(/\|/g, "\\|")}\` |`), "");
    }
    if (s.fields.length) lines.push("This step fills:", "", ...s.fields.map(field), "");
    if (s.test) {
      lines.push("Its **Test** button checks the values work before the page moves on. A step you skip stays on the Admin Panel's checklist.", "");
    } else if (s.need === "optional") {
      lines.push("You can skip this step and come back to it from the Admin Panel.", "");
    }
  });
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** The index page. */
export function renderIndex(lists) {
  const rows = lists.map((l) => `| [${prose(l.label)}](${l.id}.md) | ${l.kind === "module" ? "module (switch)" : "choose on the Modules page"} | ${proseCell(l.description)} |`);
  return [GENERATED, "", "# Platforms and payments", "",
    "One page per platform and payment provider, made from the same lists as the setup pages, so the two always agree.",
    "", "| Page | How it is turned on | What it is for |", "|---|---|---|", ...rows, ""].join("\n");
}

/** Every generated file: name → content. */
export function renderAll() {
  const problems = setupProblems({ modules: MODULES, core: SETUP_CORE, keys: INSTANCE_KEYS });
  if (problems.length) throw new Error(`gen-platform-docs: the setup lists have problems:\n  ${problems.join("\n  ")}`);
  const lists = setupLists();
  /** @type {Record<string, string>} */
  const files = { "README.md": renderIndex(lists) };
  for (const l of lists) files[`${l.id}.md`] = renderPage(l);
  return files;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes("--check");
  const files = renderAll();
  const present = existsSync(OUT_DIR) ? readdirSync(OUT_DIR).filter((f) => f.endsWith(".md")) : [];
  const stale = present.filter((f) => !(f in files));
  const differ = Object.entries(files).filter(([f, text]) => !existsSync(join(OUT_DIR, f)) || readFileSync(join(OUT_DIR, f), "utf8") !== text).map(([f]) => f);
  if (check) {
    if (differ.length || stale.length) {
      console.error("gen-platform-docs: docs/public/platforms/ does not match the setup lists —");
      for (const f of differ) console.error(`  ${f}: would change`);
      for (const f of stale) console.error(`  ${f}: no setup list makes this page`);
      console.error("Run: node tools/gen-platform-docs.mjs");
      process.exit(1);
    }
    console.log(`gen-platform-docs: ok — ${Object.keys(files).length} pages match the setup lists`);
  } else {
    mkdirSync(OUT_DIR, { recursive: true });
    for (const f of stale) rmSync(join(OUT_DIR, f));
    for (const [f, text] of Object.entries(files)) writeFileSync(join(OUT_DIR, f), text);
    console.log(`gen-platform-docs: wrote ${Object.keys(files).length} pages${stale.length ? `, removed ${stale.length}` : ""}`);
  }
}
